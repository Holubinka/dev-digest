#!/usr/bin/env node
/**
 * Generate server/src/db/seed-skills.ts from the canonical bodies in docs/skills/.
 *
 * The two copies exist for the same reason agent prompts have two: the markdown
 * is what a person reads and reviews, the TypeScript is what `pnpm db:seed`
 * inserts. Generating one from the other means they cannot drift the way the
 * prompt pair can.
 *
 * Run after editing any body:  node scripts/sync-seed-skills.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Order here is the order they are bound to their agent, i.e. prompt order. */
const SKILLS = [
  {
    constant: "UNCOVERED_BRANCH_RUBRIC",
    file: "uncovered-branch-rubric.md",
    name: "Uncovered branch rubric",
    type: "rubric",
    description:
      "List every branch this diff adds and name the test that covers it; report the ones with none.",
  },
  {
    constant: "BOUNDARY_AND_EDGE_CASE_RUBRIC",
    file: "boundary-and-edge-case-rubric.md",
    name: "Boundary and edge-case rubric",
    type: "rubric",
    description:
      "Check the inputs where behaviour changes without a branch saying so: zero, empty, the exact limit, a rounding half, a timezone.",
  },
  {
    constant: "ASSERTION_STRENGTH_RUBRIC",
    file: "assertion-strength-rubric.md",
    name: "Assertion strength rubric",
    type: "rubric",
    description:
      "For each test, name the smallest code change that would still let it pass; report the ones that survive.",
  },
  {
    constant: "TEST_SMELL_CATALOGUE",
    file: "test-smell-catalogue.md",
    name: "Test smell catalogue",
    type: "convention",
    description:
      "Flag tests that assert on mocks, restate the implementation, or cannot fail at all.",
  },
  {
    constant: "BREAKING_CHANGE_TAXONOMY",
    file: "breaking-change-taxonomy.md",
    name: "Breaking change taxonomy",
    type: "rubric",
    description:
      "Classify every contract change as breaking or additive, and take its severity from the table.",
  },
  {
    constant: "ROUTE_SIGNATURE_CHECKLIST",
    file: "route-signature-checklist.md",
    name: "Route signature checklist",
    type: "convention",
    description:
      "Check that a route's schema, its DTO mapping and both copies of its shared contract moved together.",
  },
];

const escape = (body) =>
  body.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const bodies = SKILLS.map((skill) => {
  const body = readFileSync(join(root, "docs/skills", skill.file), "utf8").trimEnd();
  return `/** Mirrors docs/skills/${skill.file}. */\nexport const ${skill.constant} = \`${escape(body)}\`;`;
}).join("\n\n");

const entries = SKILLS.map(
  (skill) => `  {
    name: ${JSON.stringify(skill.name)},
    description: ${JSON.stringify(skill.description)},
    type: ${JSON.stringify(skill.type)},
    body: ${skill.constant},
  },`,
).join("\n");

const file = `// GENERATED by scripts/sync-seed-skills.mjs — do not edit by hand.
// The canonical bodies live in docs/skills/*.md; re-run the script after editing
// one. The DB row is the source of truth at run time, so editing here only
// affects freshly seeded workspaces.

${bodies}

export interface SeedSkill {
  name: string;
  description: string;
  type: 'rubric' | 'convention' | 'security' | 'custom';
  body: string;
}

/**
 * The skills a fresh workspace starts with, in binding order.
 *
 * "Flakiness patterns" is deliberately absent: it ships as an archive under
 * docs/skills/flakiness-patterns/ and is imported by hand, so the import path is
 * exercised by a person rather than asserted by a fixture.
 */
export const SEED_SKILLS: SeedSkill[] = [
${entries}
];
`;

writeFileSync(join(root, "server/src/db/seed-skills.ts"), file);
console.log(`wrote server/src/db/seed-skills.ts (${SKILLS.length} skills)`);
